export function staffingFor(day: CoverageDay, rotation: RotationFilter) {
  if (rotation === 'all') {
    return {
      assigned: day.day.assigned + day.evening.assigned + day.night.assigned,
      required: day.day.required + day.evening.required + day.night.required,
    }
  }
  return day[rotation]
}
